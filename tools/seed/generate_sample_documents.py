SAMPLE_MARK = "TÀI LIỆU MẪU – KHÔNG CÓ GIÁ TRỊ THANH TOÁN / SAMPLE DOCUMENT"


def pdf(path: Path, title: str, issuer: list[str], rows: list[tuple[str, str]], table: list[list[str]] | None = None,
        footer: list[str] | None = None) -> None:
    c = canvas.Canvas(str(path), pagesize=A4)
    width, height = A4
    c.setTitle(title)
    c.setFillColorRGB(0.75, 0.1, 0.1)
    c.setFont("DejaVu-Bold", 9)
    c.drawCentredString(width / 2, height - 30, SAMPLE_MARK)
    c.setFillColorRGB(0, 0, 0)
    y = height - 60
    c.setFont("DejaVu-Bold", 11)
    for line in issuer:
        c.drawString(50, y, line)
        c.setFont("DejaVu", 9)
        y -= 14
    y -= 16
    c.setFont("DejaVu-Bold", 16)
    c.drawCentredString(width / 2, y, title)
    y -= 34
    for key, value in rows:
        c.setFont("DejaVu", 10)
        c.drawString(50, y, f"{key}:")
        c.setFont("DejaVu-Bold", 10)
        c.drawString(230, y, value)
        y -= 18
    if table:
        y -= 10
        col = [50, 90, 300, 360, 430]
        c.setFont("DejaVu-Bold", 9)
        for i, cell in enumerate(table[0]):
            c.drawString(col[i], y, cell)
        c.line(50, y - 4, width - 50, y - 4)
        y -= 18
        c.setFont("DejaVu", 9)
        for row in table[1:]:
            for i, cell in enumerate(row):
                c.drawString(col[i], y, cell)
            y -= 16
        c.line(50, y + 8, width - 50, y + 8)
        y -= 10
    for line in footer or []:
        c.setFont("DejaVu-Bold", 10)
        c.drawString(50, y, line)
        y -= 18
    c.setFont("DejaVu", 8)
    c.drawString(50, 40, "Chứng từ hư cấu do EcoTrace tạo để demo. Fictional document generated by EcoTrace for demos.")
    c.showPage()
    c.save()


def photo(path: Path, title: str, lines: list[str]) -> None:
    """A slightly rotated, blurred 'phone photo' of a paper slip, so the AI has to read an image."""
    font = ImageFont.truetype(str(FONT_DIR / "DejaVuSans.ttf"), 26)
    bold = ImageFont.truetype(str(FONT_DIR / "DejaVuSans-Bold.ttf"), 34)
    small = ImageFont.truetype(str(FONT_DIR / "DejaVuSans-Bold.ttf"), 18)
    paper = Image.new("RGB", (900, 120 + 46 * len(lines) + 80), (252, 250, 240))
    draw = ImageDraw.Draw(paper)
    draw.text((30, 20), SAMPLE_MARK, font=small, fill=(180, 30, 30))
    draw.text((450, 75), title, font=bold, fill=(20, 20, 20), anchor="mm")
    y = 130
    for line in lines:
        draw.text((40, y), line, font=font, fill=(35, 35, 45))
        y += 46
    background = Image.new("RGB", (paper.width + 160, paper.height + 160), (96, 104, 112))
    background.paste(paper.rotate(2.5, expand=True, fillcolor=(96, 104, 112)), (60, 50))
    background.filter(ImageFilter.GaussianBlur(0.8)).save(path, quality=88)


